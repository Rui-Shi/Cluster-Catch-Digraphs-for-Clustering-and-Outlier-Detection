#!/usr/bin/env Rscript
# 64_nn_provenance_gen.R -- generate the fresh NN quantile-table REPLICATE
# CLOUDS that the alpha-provenance discriminator (65_nn_provenance_test.R)
# needs.
#
# WHY THIS FILE EXISTS
# --------------------
# 62_audit_nn_duplicates.R established that 21 pairs of shipped NN quantile
# tables (R/NN-test_quantile/NN-test-simul_<d>d_{99,999}%.RData and the
# {95,99}% pairs at d=6..9) are identical in content -- one Monte Carlo run
# saved twice under two level names. For 13 of the paper's 16 real data sets
# the alpha that produced the published result is therefore NOT readable off
# the filename, and Table tab:alpha_real's per-data-set alpha claim is
# unverified. This script produces the reference material needed to test it.
#
# THE DESIGN DECISION THIS FILE EMBODIES
# --------------------------------------
# 46_verify_wp2a_alpha.R tried to identify the surviving level by comparing a
# duplicated dimension's table against a NEIGHBOURING dimension's known pair.
# That failed: the per-unit-dimension effect (0.01734) swamps the alpha effect
# (0.00185) by 9.4x, so the comparison measured dimension, not alpha. The fix
# is to compare WITHIN a dimension against a REPLICATE CLOUD -- R independent
# fresh runs at each candidate level -- which supplies the noise scale that
# attempt lacked. This file generates that cloud.
#
# Three properties make the cloud cheap and the comparison fair:
#
#   1. ONE MC RUN SERVES EVERY ALPHA. 01i_nn_multiquant_table.R's
#      nn_mc_draws() returns the raw draw matrices and nn_multiquant()
#      reduces the SAME draws at every requested level, so the 95%, 99% and
#      99.9% tables of a replicate are perfectly paired: any difference
#      between them is the alpha, with zero Monte-Carlo noise between the
#      levels. Level pairs generated by separate runs could never say that.
#
#   2. THE TABLE ENTRY AT SUBSAMPLE SIZE k DOES NOT DEPEND ON THE n THE TABLE
#      WAS GENERATED AT. The generator (R/ccds/NN_Dist_Est.R:24-33, transcribed
#      verbatim as nn_simu_once_orig) draws a FRESH sample of size x for every
#      x in 1..n and reduces column x from that sample alone. Column k is
#      therefore an independent MC estimate of the same population quantity
#      whatever n was. The shipped tables were built at n=5000; we build at
#      n=1013, which costs (1013/5000)^3 = 0.83% as much and still covers
#      every data set in this tier (largest is shuffle, n=1013).
#
#   3. COLUMNS ARE INDEPENDENT ACROSS k. Same reason: separate samples. So a
#      pointwise sign test over k has ~n genuinely independent trials, which
#      is where the discriminating power comes from.
#
# DEVIATION FROM THE COMMISSIONED n VALUES, AND WHY
# -------------------------------------------------
# The brief specified a per-dimension n equal to the largest data set served
# there (74 at d=19, 148 at d=18, 240 at d=6, 336 at d=7, 555 at d=8, 1013 at
# d=9). We generate every dimension at n=1013 instead. Reason: the number of
# informative subsample sizes k IS the sample size of the sign test, and at
# 24 cores the whole eight-dimension sweep costs minutes either way. Using a
# common n also makes the positive control at d=10/20 directly comparable to
# the unknown dimensions instead of being run on a different k-range. n=1013
# is a superset of every commissioned n, so nothing is lost.
#
# WHAT IS GENERATED
#   dimensions 6,7,8,9,18,19  -- the six unknown-alpha dimensions in this tier
#   dimensions 10,20          -- POSITIVE CONTROL: their shipped 99%/999%
#                                pairs are genuinely distinct, so the true
#                                label is known from the filename and the
#                                discriminator can be scored against it.
#   R = 8 replicates x niter = 250 per replicate, tokens 95/99/999 from the
#   same draws, plus the raw draws (pooled across replicates this gives 2000
#   draws per (d,k) -- the reference distribution for the level estimator in
#   65_nn_provenance_test.R).
#
# OUTPUT LAYOUT (new directory; R/NN-test_quantile is never touched)
#   R/NN-test_quantile_provenance/rep<RR>/NN-test-simul_<d>d_<tok>%.RData
#   R/NN-test_quantile_provenance/rep<RR>/NN-draws_<d>d_n<n>.RData
#   revision_experiments/results/tr1/wp2a_provenance_gen_manifest.csv
#
# CRASH SAFETY (G: is an external enclosure that has dropped off the bus under
# sustained write load). Every file is written to <name>.part and then
# file.rename()d into place, which is atomic on NTFS, so a half-written table
# can never be mistaken for a finished one. The manifest row is appended after
# each (d, replicate) cell, not buffered. The script is RESUMABLE: a cell
# whose four target files all exist is skipped without recomputation.
#
# REPRODUCIBILITY. seed = 20260810 + 1000*replicate + d, distinct per cell and
# recorded, together with (niter, cores, engine), in each file's metadata and
# in the manifest. Note 01i's header warning: the parallel path uses
# clusterSetRNGStream (L'Ecuyer-CMRG) and is reproducible only for a FIXED
# (niter, cores, seed) triple -- it is not the serial Mersenne-Twister stream.
# The estimator is unaffected; only the particular draws are.
#
# CLI
#   Rscript revision_experiments/64_nn_provenance_gen.R <d,csv> <rep,csv> [n] [niter] [cores]
#   defaults: n = 1013, niter = 250, cores = min(24, detectCores())
#   e.g.  Rscript revision_experiments/64_nn_provenance_gen.R 9 1,2,3
#         Rscript revision_experiments/64_nn_provenance_gen.R 6,7,8 1,2,3,4,5,6,7,8

suppressPackageStartupMessages({
  library(here)
  library(parallel)
})

source(here::here("revision_experiments/01i_nn_multiquant_table.R"))

OUTROOT   <- here::here("R/NN-test_quantile_provenance")
MANIFEST  <- here::here("revision_experiments/results/tr1/wp2a_provenance_gen_manifest.csv")
# Default level set. Overridable on the CLI (6th argument) purely so the
# second positive control at d=5, whose shipped distinct pair is 90%/95% and
# not 99%/999%, can be generated at the levels it needs. Changing this default
# would make every already-generated cell look incomplete and silently
# retrigger 64 cells of Monte Carlo -- so it is a per-invocation argument, not
# an edit to the default.
QUANTS    <- c(0.95, 0.99, 0.999)
ENGINE    <- "orig_list"

rep_dir   <- function(r) file.path(OUTROOT, sprintf("rep%02d", r))
tab_path  <- function(r, d, tok) file.path(rep_dir(r), sprintf("NN-test-simul_%dd_%s%%.RData", d, tok))
draw_path <- function(r, d, n)   file.path(rep_dir(r), sprintf("NN-draws_%dd_n%d.RData", d, n))
cell_seed <- function(r, d) as.integer(20260810L + 1000L * r + d)

#' Atomic save: write to <path>.part, then rename. file.rename() on NTFS
#' replaces the target in one metadata operation, so a reader never observes a
#' partially written .RData.
save_atomic <- function(objs, path) {
  part <- paste0(path, ".part")
  if (file.exists(part)) unlink(part)
  e <- list2env(objs, parent = emptyenv())
  save(list = names(objs), envir = e, file = part)
  if (!file.rename(part, path)) {
    unlink(part)
    stop("save_atomic(): rename failed for ", path)
  }
  invisible(path)
}

cell_complete <- function(r, d, n) {
  all(file.exists(c(vapply(TOKENS, function(t) tab_path(r, d, t), ""), draw_path(r, d, n))))
}

#' Generate one (dimension, replicate) cell.
run_cell <- function(d, r, n, niter, cores) {
  if (cell_complete(r, d, n)) {
    cat(sprintf("[skip, complete] d=%d rep=%02d n=%d\n", d, r, n)); flush.console()
    return(invisible("skip"))
  }
  dir.create(rep_dir(r), recursive = TRUE, showWarnings = FALSE)
  seed <- cell_seed(r, d)
  cat(sprintf("GEN d=%d rep=%02d n=%d niter=%d cores=%d seed=%d ... ", d, r, n, niter, cores, seed))
  flush.console()

  draws <- nn_mc_draws(n = n, d = d, niter = niter, cores = cores, seed = seed, engine = ENGINE)
  tabs  <- nn_multiquant(draws, QUANTS)

  # Sanity: the lower-tail quantile must be monotone DECREASING as the level
  # gets more extreme (0.95 -> p=0.05 sits above 0.999 -> p=0.001), pointwise
  # and per replicate. This is what makes the A/B clouds signed rather than
  # merely different, and it is the premise of the sign test in 65. Check it,
  # do not assume it.
  qo <- order(QUANTS); ord_toks <- TOKENS[qo]
  mono_ok <- TRUE
  for (i in seq_len(length(ord_toks) - 1L)) {
    mono_ok <- mono_ok &&
      all(tabs[[ord_toks[i]]]$average >= tabs[[ord_toks[i + 1L]]]$average) &&
      all(tabs[[ord_toks[i]]]$median  >= tabs[[ord_toks[i + 1L]]]$median)
  }
  if (!mono_ok) stop(sprintf("d=%d rep=%d: quantile levels are not pointwise monotone -- reduction is wrong", d, r))

  for (tok in TOKENS) {
    simul <- tabs[[tok]]
    attr(simul, "nn_multiquant_meta") <- c(draws$meta,
                                           list(quant = nn_q_of_token(tok), replicate = r,
                                                script = "64_nn_provenance_gen.R"))
    save_atomic(list(simul = simul), tab_path(r, d, tok))
  }
  save_atomic(list(NN.dist.ave.mat = draws$ave,
                   NN.dist.med.mat = draws$med,
                   nn_meta = c(draws$meta, list(replicate = r, script = "64_nn_provenance_gen.R"))),
              draw_path(r, d, n))

  fz <- function(tok) if (tok %in% names(tabs)) mean(tabs[[tok]]$average[-1] == 0) else NA_real_
  row <- data.frame(
    d = d, replicate = r, n = n, niter = niter, cores = cores, seed = seed,
    engine = ENGINE, tokens = paste(TOKENS, collapse = "/"),
    elapsed_sec = draws$meta$elapsed_sec, sec_per_iter = draws$meta$sec_per_iter,
    # Fixed manifest schema (NA where a token was not requested) so that runs
    # with different QUANTS still append to one CSV without shifting columns.
    frac_zero_avg_95  = fz("95"), frac_zero_avg_99 = fz("99"), frac_zero_avg_999 = fz("999"),
    monotone_ok = mono_ok,
    timestamp = format(Sys.time()), stringsAsFactors = FALSE)
  dir.create(dirname(MANIFEST), recursive = TRUE, showWarnings = FALSE)
  if (!file.exists(MANIFEST)) write.csv(row, MANIFEST, row.names = FALSE) else
    write.table(row, MANIFEST, sep = ",", col.names = FALSE, row.names = FALSE, append = TRUE, qmethod = "double")

  cat(sprintf("done %.1fs (%.4f s/iter)\n", draws$meta$elapsed_sec, draws$meta$sec_per_iter))
  flush.console()
  invisible("ok")
}

# ---------------------------------------------------------------------------
args <- commandArgs(trailingOnly = TRUE)
if (length(args) < 2) {
  stop("Usage: Rscript revision_experiments/64_nn_provenance_gen.R <d,csv> <rep,csv> [n] [niter] [cores] [quants,csv]", call. = FALSE)
}
DS     <- as.integer(strsplit(args[[1]], ",")[[1]])
REPS   <- as.integer(strsplit(args[[2]], ",")[[1]])
NGEN   <- if (length(args) >= 3) as.integer(args[[3]]) else 1013L
NITER  <- if (length(args) >= 4) as.integer(args[[4]]) else 250L
CORES  <- if (length(args) >= 5) as.integer(args[[5]]) else min(24L, parallel::detectCores())
if (length(args) >= 6) QUANTS <- as.numeric(strsplit(args[[6]], ",")[[1]])
TOKENS <- nn_token_of_q(QUANTS)

cat(sprintf("=== 64_nn_provenance_gen.R === d=%s reps=%s n=%d niter=%d cores=%d tokens=%s\noutroot=%s\n",
            paste(DS, collapse = ","), paste(REPS, collapse = ","), NGEN, NITER, CORES,
            paste(TOKENS, collapse = "/"), OUTROOT))
t0 <- Sys.time()
for (d in DS) for (r in REPS) run_cell(d, r, NGEN, NITER, CORES)
cat(sprintf("ALL_CELLS_COMPLETE total=%.1fs\n", as.numeric(difftime(Sys.time(), t0, units = "secs"))))
