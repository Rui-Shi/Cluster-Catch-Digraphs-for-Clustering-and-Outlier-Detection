#!/usr/bin/env Rscript
# 72_verify_regen999.R -- acceptance test for the staged alpha=0.1% tables
# produced by 71, run BEFORE anything is installed into R/NN-test_quantile.
#
# The defect being repaired is a table whose contents do not match its name.
# Generating a replacement and trusting its filename would repeat exactly that
# mistake, so each staged table has to be read back and shown to hold the level
# it claims. Three tests, in increasing order of what they can catch.
#
# TEST 1 -- CALIBRATION AGAINST A KNOWN ANSWER. 71 reduces one Monte Carlo run
# at 0.95, 0.99 and 0.999. The "99" output is therefore a fresh 1% table at a
# dimension where the shipped 1% table's content is independently established
# (WP2_RESULTS section 9). If the new generator, engine and iteration count are
# sound, new-99 must agree closely with shipped-99. This is the test that
# validates the machinery, because it is the only one with a known right
# answer. A failure here voids everything else.
#
# TEST 2 -- ORDERING. The 0.1% lower-tail quantile must sit at or below the 1%
# quantile at every subsample size. Cheap, and it catches a token/level mix-up
# in the reduction immediately.
#
# TEST 3 -- DIRECT LEVEL READ, AGAINST INDEPENDENT DRAWS. The estimator from
# 67: level_k = mean(draws_k <= table_k), median over k. Crucially the draws
# come from R/NN-test_quantile_provenance/, generated by 64 in a different run
# with different seeds -- NOT from 71's own draws, against which every table
# would score correctly by construction. Those replicates reach n=555, so the
# read is over the first 555 subsample sizes. Pooled depth is ~2000 draws, so
# the resolution near 0.001 is coarse; the test is whether the new table reads
# an order of magnitude below the shipped one, which is precisely the
# distinction that was wrong before.
#
# Read-only apart from its own CSV. Installs nothing.

suppressMessages(library(here))
STAGE <- here::here("R/NN-test_quantile_regen999")
SHIP  <- here::here("R/NN-test_quantile")
PDIR  <- here::here("R/NN-test_quantile_provenance")
OUT   <- here::here("revision_experiments/results/tr1/wp2c_regen999_verify.csv")

load1 <- function(p, obj = "simul") { e <- new.env(); load(p, envir = e); get(obj, envir = e) }
shipf  <- function(d, tok) file.path(SHIP, sprintf("NN-test-simul_%dd_%s%%.RData", d, tok))

#' A completed 71 run writes straight into <d>d/; a partial pool from 74 writes
#' into <d>d/pooled_n<niter>/. Prefer the deepest pool available, so a
#' dimension still generating can be verified at the depth it has reached.
stagef <- function(d, tok) {
  direct <- file.path(STAGE, sprintf("%dd", d), sprintf("NN-test-simul_%dd_%s%%.RData", d, tok))
  if (file.exists(direct)) return(direct)
  pools <- list.files(file.path(STAGE, sprintf("%dd", d)), pattern = "^pooled_n[0-9]+$",
                      full.names = TRUE)
  if (!length(pools)) return(direct)
  pools <- pools[order(-as.integer(sub(".*pooled_n", "", pools)))]
  cands <- file.path(pools, sprintf("NN-test-simul_%dd_%s%%.RData", d, tok))
  hit <- cands[file.exists(cands)]
  if (length(hit)) hit[1] else direct
}

reps <- sort(list.files(PDIR, pattern = "^rep[0-9]+$"))
pool_draws <- function(d) {
  fs <- unlist(lapply(reps, function(r)
    list.files(file.path(PDIR, r), pattern = sprintf("^NN-draws_%dd_n[0-9]+\\.RData$", d),
               full.names = TRUE)))
  if (!length(fs)) return(NULL)
  do.call(rbind, lapply(fs, load1, obj = "NN.dist.ave.mat"))
}
level_curve <- function(tab, draws) {
  K <- min(length(tab), ncol(draws))
  vapply(seq_len(K), function(k) mean(draws[, k] <= tab[k]), numeric(1))
}

dims <- sort(as.integer(sub("d$", "", list.files(STAGE, pattern = "^[0-9]+d$"))))
if (!length(dims)) { cat("no staged dimensions found under ", STAGE, "\n"); quit(status = 1) }
cat(sprintf("staged dimensions: %s\n\n", paste(dims, collapse = ", ")))

rows <- list()
for (d in dims) {
  f999 <- stagef(d, "999"); f99 <- stagef(d, "99")
  if (!file.exists(f999) || !file.exists(f99)) { cat(sprintf("d=%d incomplete, skipped\n", d)); next }
  new999 <- load1(f999); new99 <- load1(f99)
  n <- length(new999$average)

  cat(sprintf("=== d=%d  (n=%d) ===\n", d, n))

  # ---- TEST 1: new 1% vs shipped 1% ---------------------------------------
  s99 <- if (file.exists(shipf(d, "99"))) load1(shipf(d, "99")) else NULL
  if (is.null(s99)) {
    # at d=21 the "99" file was removed as a duplicate; its identical twin
    # survives under the "999" name and holds the same 1% content
    s99 <- if (file.exists(shipf(d, "999"))) load1(shipf(d, "999")) else NULL
  }
  t1_rel <- NA
  if (!is.null(s99)) {
    K <- min(n, length(s99$average))
    a <- new99$average[2:K]; b <- s99$average[2:K]   # index 1 is a structural 0
    t1_rel <- median(abs(a - b) / b)
    cat(sprintf("  T1 new-99 vs shipped-99 : median |rel diff| = %.4f over %d sizes  -> %s\n",
                t1_rel, K - 1, if (t1_rel < 0.02) "PASS" else "*** FAIL ***"))
  } else cat("  T1 no shipped 1% table to compare against -- SKIPPED\n")

  # ---- TEST 2: 0.1% must not exceed 1% ------------------------------------
  viol <- sum(new999$average[-1] > new99$average[-1] + 1e-12)
  cat(sprintf("  T2 ordering 999 <= 99    : %d violations of %d           -> %s\n",
              viol, n - 1, if (viol == 0) "PASS" else "*** FAIL ***"))

  # ---- TEST 3: direct level read against independent draws ----------------
  lvl_new <- lvl_ship <- NA; ndraw <- 0L
  D <- pool_draws(d)
  if (!is.null(D)) {
    ndraw <- nrow(D)
    lvl_new <- median(level_curve(new999$average, D))
    sship <- if (file.exists(shipf(d, "999"))) load1(shipf(d, "999")) else NULL
    if (!is.null(sship)) lvl_ship <- median(level_curve(sship$average, D))
    cat(sprintf("  T3 level of new 999      : %.5f  (target 0.001)         -> %s\n",
                lvl_new, if (!is.na(lvl_new) && lvl_new < 0.004) "PASS" else "*** FAIL ***"))
    if (!is.na(lvl_ship))
      cat(sprintf("     level of shipped 999  : %.5f  (the mislabelling: reads as 1%%)\n", lvl_ship))
    cat(sprintf("     pooled independent draws = %d, k = 1..%d\n", ndraw, min(n, ncol(D))))
  } else cat("  T3 no independent replicate draws at this d -- SKIPPED\n")

  rows[[length(rows) + 1]] <- data.frame(
    d = d, n = n, t1_median_rel_diff = t1_rel, t2_violations = viol,
    t3_level_new999 = lvl_new, t3_level_shipped999 = lvl_ship,
    t3_pooled_draws = ndraw,
    pass = (is.na(t1_rel) || t1_rel < 0.02) && viol == 0 &&
           (is.na(lvl_new) || lvl_new < 0.004),
    stringsAsFactors = FALSE)
  cat("\n")
}

res <- do.call(rbind, rows)
cat("=== summary ===\n"); print(res, row.names = FALSE, digits = 4)
write.csv(res, OUT, row.names = FALSE)
cat(sprintf("\nwrote %s\n", OUT))
cat(sprintf("OVERALL: %s\n", if (all(res$pass)) "all staged tables accepted -- safe to install"
                             else "*** ONE OR MORE TABLES REJECTED -- do not install ***"))
