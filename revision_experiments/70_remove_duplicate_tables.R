#!/usr/bin/env Rscript
# 70_remove_duplicate_tables.R -- delete the redundant member of each duplicated
# NN quantile pair, but only where nothing loads it.
#
# CONTEXT. 21 pairs of NN quantile tables hold identical content under two
# different level names (d = 6-9 as 95/99, d = 11-19 and 21-28 as 99/999).
# The user asked for the redundant copies to be removed. Deletion is safe only
# where the resolvers never ask for the deleted token, and that is not true
# everywhere:
#
#   d = 6-9    UN and SUN both load "95"   -> "99"  is dead weight, DELETE
#   d = 21-28  UN and SUN both load "999"  -> "99"  is dead weight, DELETE
#   d = 11-19  UN loads "99", SUN loads "999" -> BOTH are live, KEEP BOTH
#
# get_simul() (harness.R ~283) builds the path from the token and stop()s if
# the file is absent, so a wrong deletion is a hard failure at run time, not a
# silent fallback. The d = 11-19 group is therefore left alone and escalated.
#
# EVIDENCE OUTLIVES THE FILES. Once a duplicate is gone, the fact that it WAS a
# duplicate is no longer checkable on disk. Every deletion is recorded first --
# both paths, sizes, MD5s, and a fresh content comparison made at delete time,
# not copied from an earlier run -- into a tracked markdown manifest. (The
# results/ tree is gitignored and *.RData is gitignored, so a manifest written
# anywhere else would not survive in the repository.)
#
# The script refuses to delete anything whose content does not match its
# surviving sibling at the moment of deletion.
#
# USAGE
#   Rscript 70_remove_duplicate_tables.R           # dry run, prints the plan
#   Rscript 70_remove_duplicate_tables.R --apply   # performs the deletions

suppressMessages(library(here))
source(here::here("revision_experiments/harness.R"))
source(here::here("revision_experiments/wp0_mccd_methods.R"))

APPLY  <- "--apply" %in% commandArgs(trailingOnly = TRUE)
NNDIR  <- here::here("R/NN-test_quantile")
MANI   <- here::here("revision_experiments/DELETED_DUPLICATE_TABLES.md")
nnf    <- function(d, tok) file.path(NNDIR, sprintf("NN-test-simul_%dd_%s%%.RData", d, tok))
load1  <- function(p) { e <- new.env(); load(p, envir = e); get("simul", envir = e) }

# the pair at each duplicated dimension, lower token first
PAIRS <- rbind(
  data.frame(d = 6:9,   lo = "95", hi = "99"),
  data.frame(d = 11:19, lo = "99", hi = "999"),
  data.frame(d = 21:28, lo = "99", hi = "999")
)

plan <- list()
for (i in seq_len(nrow(PAIRS))) {
  d <- PAIRS$d[i]; lo <- PAIRS$lo[i]; hi <- PAIRS$hi[i]
  un <- nn_quant_label_paper_UN(d); sun <- nn_quant_label_paper_SUN(d)
  live <- unique(c(un, sun))
  dead <- setdiff(c(lo, hi), live)
  plan[[i]] <- data.frame(
    d = d, lo = lo, hi = hi, UN_loads = un, SUN_loads = sun,
    n_live_tokens = length(live),
    action = if (length(dead) == 1) sprintf("DELETE %s", dead) else "KEEP BOTH (both live)",
    delete_token = if (length(dead) == 1) dead else NA_character_,
    stringsAsFactors = FALSE)
}
plan <- do.call(rbind, plan)
cat("=== plan ===\n"); print(plan[, c("d","lo","hi","UN_loads","SUN_loads","action")],
                            row.names = FALSE)
todo <- plan[!is.na(plan$delete_token), ]
cat(sprintf("\n  deletable: %d ; retained because both tokens are live: %d\n",
            nrow(todo), sum(is.na(plan$delete_token))))

# ---- verify each deletion candidate is genuinely redundant, right now -------
cat("\n=== pre-deletion verification ===\n")
recs <- list()
for (i in seq_len(nrow(todo))) {
  d <- todo$d[i]; del <- todo$delete_token[i]
  keep <- setdiff(c(todo$lo[i], todo$hi[i]), del)
  fd <- nnf(d, del); fk <- nnf(d, keep)
  if (!file.exists(fd) || !file.exists(fk)) {
    cat(sprintf("  d=%-2d SKIP -- a file is already absent\n", d)); next
  }
  a <- load1(fd); b <- load1(fk)
  same <- identical(a$average, b$average) && identical(a$median, b$median)
  recs[[length(recs) + 1]] <- data.frame(
    d = d, deleted_token = del, kept_token = keep,
    deleted_file = basename(fd), kept_file = basename(fk),
    bytes = file.size(fd), md5_deleted = unname(tools::md5sum(fd)),
    md5_kept = unname(tools::md5sum(fk)), content_identical = same,
    stringsAsFactors = FALSE)
  cat(sprintf("  d=%-2d delete %-4s keep %-4s  identical=%s  md5 match=%s\n",
              d, del, keep, same, tools::md5sum(fd) == tools::md5sum(fk)))
}
rec <- do.call(rbind, recs)
if (any(!rec$content_identical)) {
  cat("\n*** ABORT: a deletion candidate is NOT identical to its sibling ***\n"); quit(status = 1)
}

# ---- manifest --------------------------------------------------------------
w <- function(...) cat(sprintf(...), file = MANI, append = TRUE)
if (APPLY) {
  cat("", file = MANI)
  w("# Deleted duplicate NN quantile tables\n\n")
  w("Generated by `revision_experiments/70_remove_duplicate_tables.R` on %s.\n\n",
    format(Sys.Date()))
  w("21 pairs of NN quantile tables held identical content under two level\n")
  w("names -- one Monte Carlo run saved twice. The redundant member is removed\n")
  w("**only where no resolver asks for that token**. This file is the record:\n")
  w("once a duplicate is gone, its having been a duplicate is no longer\n")
  w("checkable on disk. Content identity below was re-verified at delete time.\n\n")
  w("The alpha level each pair actually holds was recovered independently and\n")
  w("is documented in `WP2_RESULTS.md` section 9: 5%% at d = 6-9, 1%% at\n")
  w("d = 12, 16, 18, 19, 21.\n\n")
  w("## Deleted\n\n")
  w("| d | deleted | kept | bytes | MD5 (both) | identical |\n")
  w("|---|---|---|---|---|---|\n")
  for (i in seq_len(nrow(rec)))
    w("| %d | `%s` | `%s` | %s | `%s` | %s |\n", rec$d[i], rec$deleted_file[i],
      rec$kept_file[i], format(rec$bytes[i], big.mark = ","),
      substr(rec$md5_deleted[i], 1, 16), rec$content_identical[i])
  w("\n## Retained despite being duplicates\n\n")
  w("At d = 11-19 **both** tokens are live -- UN-MCCD resolves to `99` and\n")
  w("SUN-MCCD to `999` (`wp0_mccd_methods.R:185,190`). `get_simul()` stop()s on\n")
  w("a missing file, so deleting either member breaks one of the two methods.\n")
  w("These nine pairs are left intact:\n\n")
  for (d in 11:19) w("- d = %d: `NN-test-simul_%dd_99%%.RData` (UN) and `NN-test-simul_%dd_999%%.RData` (SUN) -- identical content, both loaded\n", d, d, d)
  w("\n")
}

# ---- delete ----------------------------------------------------------------
if (!APPLY) {
  cat("\nDRY RUN -- nothing deleted. Re-run with --apply.\n"); quit(status = 0)
}
cat("\n=== deleting ===\n")
for (i in seq_len(nrow(rec))) {
  f <- file.path(NNDIR, rec$deleted_file[i])
  ok <- file.remove(f)
  cat(sprintf("  %-34s removed=%s\n", rec$deleted_file[i], ok))
}
cat(sprintf("\nmanifest written to %s\n", MANI))
cat("done -- now run 69_verify_table_inventory.R\n")
