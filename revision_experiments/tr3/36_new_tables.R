#!/usr/bin/env Rscript
# revision_experiments/tr3/36_new_tables.R
#
# LaTeX tabular bodies for the new experiments of the KBS rebuttal, from their
# result files (nothing is rerun). Each part is written only if its inputs exist.
#   ablation  ablation_direction_summary.csv (34_ablation_direction.R)
#   paired    paired_tests.csv (35_paired_tests.R)
#   type1     type1_test_summary.csv, type1_ccd_summary.csv (33_type1.R)
#   realhd    real_hd.csv (31_hd_real.R), real_hd_baselines.csv (32_hd_baselines.R)
# Checks: the ablation table has 12 cells of 500 replicates, and its descending
# ARI and SR (3 decimals) equal the n = 200 rows of the supplement's UN-CCD
# tables (SUPP_TEX, default the manuscript folder); the paired table has 60
# tests (30 cells x 2 comparisons).
#
# USAGE (from the clone root): Rscript revision_experiments/tr3/36_new_tables.R
# OUTPUT: results/tr3/tex/new_<part>.tex (one tabular body each; the manuscript
# wraps each tabular in \textcolor{blue}{...}) and a summary on stdout.

source(here::here("revision_experiments/tr3/tr3_lib.R"))

SUPP_TEX <- Sys.getenv("SUPP_TEX", "G:/Submissions/TR3/TR3_10182026/Supplementary_Material.tex")
OUT <- tr3_path("tex")
dir.create(OUT, showWarnings = FALSE)
f3 <- function(x) { x <- as.numeric(x); s <- sprintf("%.3f", x); s[s == "-0.000"] <- "0.000"; s }
DIST <- c(uniform = "Uniform", gaussian = "Gaussian")
emit <- function(part, lines) {
  out <- file.path(OUT, paste0("new_", part, ".tex"))
  writeLines(c(paste0("% generated by revision_experiments/tr3/36_new_tables.R (", part, "); do not edit"),
               lines), out, useBytes = TRUE)
  cat("written:", out, "\n")
}
have <- function(...) all(file.exists(tr3_path(c(...))))

# --- ablation: ascending vs descending search, n = 200 ----------------------
if (have("ablation_direction_summary.csv")) {
  a <- utils::read.csv(tr3_path("ablation_direction_summary.csv"), colClasses = "character")
  stopifnot(nrow(a) == 12, all(a$reps == "500"), all(a$n == "200"))
  a <- a[order(match(a$dist, names(DIST)), as.integer(a$d), as.integer(a$n_clusters)), ]
  sr <- function(p) f3(as.numeric(p) / 100)
  rows <- sprintf("%s & %s & %s & %s & %s & %s & %s & %s \\\\",
                  DIST[a$dist], a$d, a$n_clusters,
                  f3(a$descend_mean_ari), f3(a$ascend_mean_ari),
                  sr(a$descend_pct_correct_k), sr(a$ascend_pct_correct_k), f3(a$p_holm))
  # the descending columns must repeat the n = 200 rows of the supplement's UN-CCD tables
  tex <- readLines(SUPP_TEX, warn = FALSE)
  for (ds in names(DIST)) {
    lab <- sprintf("\\label{tab:%s_UN-CCDs_Apdx}", c(uniform = "uni", gaussian = "Gau")[ds])
    end <- grep(lab, tex, fixed = TRUE); stopifnot(length(end) == 1)
    beg <- max(grep("\\begin{table}", tex[seq_len(end)], fixed = TRUE))
    blk <- tex[beg:end]
    i <- grep("{$n=200$}", blk, fixed = TRUE); stopifnot(length(i) == 1)
    for (j in 0:2) {
      cells <- trimws(strsplit(gsub("\\\\textcolor\\{red\\}\\{([^}]*)\\}", "\\1",
                                    sub("\\\\\\\\.*$", "", blk[i + j])), "&")[[1]])
      k <- sub(" clusters", "", cells[2])
      for (d in c("10", "20")) {
        off <- 2 + 3 * match(d, c("2", "3", "5", "10", "20")) - 2
        r <- a[a$dist == ds & a$d == d & a$n_clusters == k, ]
        got <- c(f3(r$descend_mean_ari), f3(as.numeric(r$descend_pct_correct_k) / 100))
        want <- cells[c(off, off + 2)]
        if (!identical(got, want)) stop("ablation descend differs from the supplement: ", ds, " d=", d, " k=", k,
                                        " (", paste(got, collapse = "/"), " vs ", paste(want, collapse = "/"), ")")
      }
    }
  }
  cat("check passed: descending ARI and SR equal the supplement's UN-CCD tables at n = 200 (12 cells)\n")
  emit("ablation", c("\\hline",
                     "Clusters & $d$ & \\# clusters & \\textit{ARI} desc. & \\textit{ARI} asc. & \\textit{SR} desc. & \\textit{SR} asc. & $p_{\\mathrm{Holm}}$ \\\\ \\hline",
                     rows, "\\hline"))
  diff <- as.numeric(a$mean_ari_diff)
  cat(sprintf("ablation: mean ARI difference (asc - desc) %.4f to %.4f; descending higher in %d of 12; Holm p < 0.05 in %d; raw p < 0.05 in %d\n",
              min(diff), max(diff), sum(diff < 0), sum(as.numeric(a$p_holm) < 0.05),
              sum(as.numeric(a$p_wilcoxon) < 0.05, na.rm = TRUE)))
}

# --- paired tests at n = 50: verdict counts per distribution and d ----------
if (have("paired_tests.csv")) {
  p <- utils::read.csv(tr3_path("paired_tests.csv"), colClasses = "character")
  stopifnot(nrow(p) == 60, all(p$n == "50"))
  V <- c("UN higher", "UN lower", "no difference")
  stopifnot(all(p$verdict %in% V))
  cnt <- function(sub, cmp) sapply(V, function(v) sum(sub$comparison == cmp & sub$verdict == v))
  rows <- character(0)
  for (ds in names(DIST)) for (d in c("2", "3", "5", "10", "20")) {
    s <- p[p$dist == ds & p$d == d, ]
    stopifnot(nrow(s) == 6)
    rows <- c(rows, sprintf("%s & %s & %s & %s \\\\", DIST[ds], d,
                            paste(cnt(s, "UN vs RK"), collapse = " & "),
                            paste(cnt(s, "UN vs KS"), collapse = " & ")))
  }
  tot <- sprintf("\\multicolumn{2}{|c|}{Total} & %s & %s \\\\",
                 paste(cnt(p, "UN vs RK"), collapse = " & "), paste(cnt(p, "UN vs KS"), collapse = " & "))
  emit("paired", c("\\hline",
                   " & & \\multicolumn{3}{c|}{UN- vs RK-CCDs} & \\multicolumn{3}{c|}{UN- vs KS-CCDs} \\\\ \\cline{3-8}",
                   "Clusters & $d$ & higher & lower & n.s. & higher & lower & n.s. \\\\ \\hline",
                   rows, "\\hline", tot, "\\hline"))
  cat(sprintf("paired: UN vs RK higher/lower/n.s. %s; UN vs KS %s; raw p < 0.05 in %d of 60, Holm in %d\n",
              paste(cnt(p, "UN vs RK"), collapse = "/"), paste(cnt(p, "UN vs KS"), collapse = "/"),
              sum(as.numeric(p$p) < 0.05), sum(as.numeric(p$p_holm) < 0.05)))
}
