#!/usr/bin/env Rscript
# revision_experiments/tr3/36_new_tables.R
#
# LaTeX tabular bodies for the new experiments of the KBS rebuttal, from their
# result files (nothing is rerun). Each part is written only if its inputs exist.
#   ablation  ablation_direction_summary.csv (34_ablation_direction.R)
#   paired    paired_tests.csv (35_paired_tests.R)
#   type1     type1_test_summary.csv, type1_ccd_summary.csv (33_type1.R)
#   realhd    real_hd.csv (31_hd_real.R), real_hd_baselines.csv (32_hd_baselines.R) and
#             their *_done.csv (finished cells only, the last copy of each)
# Checks: the ablation table has 12 cells of 500 replicates, and its descending
# ARI and SR (3 decimals) equal the n = 200 rows of the supplement's UN-CCD
# tables (SUPP_TEX, default the manuscript folder); the paired table has 60
# tests (30 cells x 2 comparisons); the type1 tables have 35 (d, m) cells of
# B = 10000 and 20 (d, n) cells of 500 replicates; the realhd table has one row
# (variant "hd") per method and data set (8 x 6) with the n and d of
# tr3_load_hd(), and K-means++ and spectral clustering return the true k.
#
# USAGE (from the clone root): Rscript revision_experiments/tr3/36_new_tables.R
# OUTPUT: results/tr3/tex/new_<part>.tex (one tabular body each; the manuscript
# wraps each tabular in \textcolor{blue}{...}) and a summary on stdout. realhd
# writes new_realhd.tex (data sets as columns, ordered by n) and
# new_realhd_data.tex (n, d and k rows for the dataset tables).
# TR3_OUT_DIR, as in the drivers, replaces results/tr3 for the inputs and the
# tex folder (used for tests).

source(here::here("revision_experiments/tr3/tr3_lib.R"))
RES <- sub("[/\\\\]+$", "", Sys.getenv("TR3_OUT_DIR", TR3_RES))
tr3_path <- function(name) file.path(RES, name)

SUPP_TEX <- Sys.getenv("SUPP_TEX", "G:/Submissions/TR3/TR3_10182026/Supplementary_Material.tex")
OUT <- tr3_path("tex")
dir.create(OUT, showWarnings = FALSE)
f3 <- function(x) { x <- as.numeric(x); s <- sprintf("%.3f", x); s[s == "-0.000"] <- "0.000"; s }
DIST <- c(uniform = "Uniform", gaussian = "Gaussian")
emit <- function(part, lines) {
  out <- file.path(OUT, paste0("new_", part, ".tex"))
  writeLines(c(paste0("% generated by revision_experiments/tr3/36_new_tables.R (", part, "); do not edit"),
               lines), out, useBytes = TRUE)
  cat("written:", out, "\n")
}
have <- function(...) all(file.exists(tr3_path(c(...))))

# --- ablation: ascending vs descending search, n = 200 ----------------------
if (have("ablation_direction_summary.csv")) {
  a <- utils::read.csv(tr3_path("ablation_direction_summary.csv"), colClasses = "character")
  stopifnot(nrow(a) == 12, all(a$reps == "500"), all(a$n == "200"))
  a <- a[order(match(a$dist, names(DIST)), as.integer(a$d), as.integer(a$n_clusters)), ]
  sr <- function(p) f3(as.numeric(p) / 100)
  rows <- sprintf("%s & %s & %s & %s & %s & %s & %s & %s \\\\",
                  DIST[a$dist], a$d, a$n_clusters,
                  f3(a$descend_mean_ari), f3(a$ascend_mean_ari),
                  sr(a$descend_pct_correct_k), sr(a$ascend_pct_correct_k), f3(a$p_holm))
  # the descending columns must repeat the n = 200 rows of the supplement's UN-CCD tables
  tex <- readLines(SUPP_TEX, warn = FALSE)
  for (ds in names(DIST)) {
    lab <- sprintf("\\label{tab:%s_UN-CCDs_Apdx}", c(uniform = "uni", gaussian = "Gau")[ds])
    end <- grep(lab, tex, fixed = TRUE); stopifnot(length(end) == 1)
    beg <- max(grep("\\begin{table}", tex[seq_len(end)], fixed = TRUE))
    blk <- tex[beg:end]
    i <- grep("{$n=200$}", blk, fixed = TRUE); stopifnot(length(i) == 1)
    for (j in 0:2) {
      cells <- trimws(strsplit(gsub("\\\\textcolor\\{red\\}\\{([^}]*)\\}", "\\1",
                                    sub("\\\\\\\\.*$", "", blk[i + j])), "&")[[1]])
      k <- sub(" clusters", "", cells[2])
      for (d in c("10", "20")) {
        off <- 2 + 3 * match(d, c("2", "3", "5", "10", "20")) - 2
        r <- a[a$dist == ds & a$d == d & a$n_clusters == k, ]
        got <- c(f3(r$descend_mean_ari), f3(as.numeric(r$descend_pct_correct_k) / 100))
        want <- cells[c(off, off + 2)]
        if (!identical(got, want)) stop("ablation descend differs from the supplement: ", ds, " d=", d, " k=", k,
                                        " (", paste(got, collapse = "/"), " vs ", paste(want, collapse = "/"), ")")
      }
    }
  }
  cat("check passed: descending ARI and SR equal the supplement's UN-CCD tables at n = 200 (12 cells)\n")
  emit("ablation", c("\\hline",
                     "Clusters & $d$ & \\# clusters & \\textit{ARI} desc. & \\textit{ARI} asc. & \\textit{SR} desc. & \\textit{SR} asc. & $p_{\\mathrm{Holm}}$ \\\\ \\hline",
                     rows, "\\hline"))
  diff <- as.numeric(a$mean_ari_diff)
  cat(sprintf("ablation: mean ARI difference (asc - desc) %.4f to %.4f; descending higher in %d of 12; Holm p < 0.05 in %d; raw p < 0.05 in %d\n",
              min(diff), max(diff), sum(diff < 0), sum(as.numeric(a$p_holm) < 0.05),
              sum(as.numeric(a$p_wilcoxon) < 0.05, na.rm = TRUE)))
}

# --- paired tests at n = 50: verdict counts per distribution and d ----------
if (have("paired_tests.csv")) {
  p <- utils::read.csv(tr3_path("paired_tests.csv"), colClasses = "character")
  stopifnot(nrow(p) == 60, all(p$n == "50"))
  V <- c("UN higher", "UN lower", "no difference")
  stopifnot(all(p$verdict %in% V))
  cnt <- function(sub, cmp) sapply(V, function(v) sum(sub$comparison == cmp & sub$verdict == v))
  rows <- character(0)
  for (ds in names(DIST)) for (d in c("2", "3", "5", "10", "20")) {
    s <- p[p$dist == ds & p$d == d, ]
    stopifnot(nrow(s) == 6)
    rows <- c(rows, sprintf("%s & %s & %s & %s \\\\", DIST[ds], d,
                            paste(cnt(s, "UN vs RK"), collapse = " & "),
                            paste(cnt(s, "UN vs KS"), collapse = " & ")))
  }
  tot <- sprintf("\\multicolumn{2}{|c|}{Total} & %s & %s \\\\",
                 paste(cnt(p, "UN vs RK"), collapse = " & "), paste(cnt(p, "UN vs KS"), collapse = " & "))
  emit("paired", c("\\hline",
                   " & & \\multicolumn{3}{c|}{UN- vs RK-CCDs} & \\multicolumn{3}{c|}{UN- vs KS-CCDs} \\\\ \\cline{3-8}",
                   "Clusters & $d$ & higher & lower & n.s. & higher & lower & n.s. \\\\ \\hline",
                   rows, "\\hline", tot, "\\hline"))
  cat(sprintf("paired: UN vs RK higher/lower/n.s. %s; UN vs KS %s; raw p < 0.05 in %d of 60, Holm in %d\n",
              paste(cnt(p, "UN vs RK"), collapse = "/"), paste(cnt(p, "UN vs KS"), collapse = "/"),
              sum(as.numeric(p$p) < 0.05), sum(as.numeric(p$p_holm) < 0.05)))
}

# --- type1: size of one MC-SRT under CSR, and k_hat of UN-CCDs on CSR data ---
if (have("type1_test_summary.csv", "type1_ccd_summary.csv")) {
  D <- c("2", "3", "5", "10", "20"); M <- c("5", "10", "20", "50", "100", "200", "500")
  N <- c("50", "100", "200", "500")
  t1 <- utils::read.csv(tr3_path("type1_test_summary.csv"), colClasses = "character")
  stopifnot(nrow(t1) == 35, all(t1$B == "10000"), setequal(paste(t1$d, t1$m), outer(D, M, paste)))
  f2 <- function(x) sprintf("%.2f", as.numeric(x))
  pct <- function(a) sub("\\.?0+$", "", sprintf("%.1f", 100 * as.numeric(a)))
  rows <- character(0)
  for (d in D) {
    s <- t1[t1$d == d, ]; s <- s[match(M, s$m), ]
    rows <- c(rows,
      sprintf("\\multirow{2}*{%s} & \\multirow{2}*{%s\\%%} & generator & %s \\\\ \\cline{3-10}", d, pct(s$alpha[1]),
              paste(f2(s$rule_over_alpha), collapse = " & ")),
      sprintf(" & & clustering & %s \\\\ \\hline", paste(f2(s$ball_rule_over_alpha), collapse = " & ")))
  }
  emit("type1_test", c("\\hline",
    sprintf("$d$ & $\\alpha$ & null & %s \\\\ \\hline", paste(sprintf("$m=%s$", M), collapse = " & ")),
    rows))
  rng <- function(x) sprintf("%.2f to %.2f", min(as.numeric(x)), max(as.numeric(x)))
  cat("type1 test: rule/alpha, generator null", rng(t1$rule_over_alpha), "; clustering null", rng(t1$ball_rule_over_alpha), "\n")
  for (d in D) cat(sprintf("  d=%s: generator %s, clustering %s\n", d,
                           rng(t1$rule_over_alpha[t1$d == d]), rng(t1$ball_rule_over_alpha[t1$d == d])))

  t2 <- utils::read.csv(tr3_path("type1_ccd_summary.csv"), colClasses = "character")
  stopifnot(nrow(t2) == 20, all(t2$n_reps == "500"), setequal(paste(t2$d, t2$n), outer(D, N, paste)))
  rows <- character(0)
  for (d in D) {
    s <- t2[t2$d == d, ]; s <- s[match(N, s$n), ]
    rows <- c(rows, sprintf("%s & %s & %s & %s \\\\", d, paste(f3(s$prop_k1), collapse = " & "),
                            paste(f2(s$mean_k_hat), collapse = " & "), paste(f3(s$mean_si), collapse = " & ")))
  }
  hdr <- paste(sprintf("$n=%s$", N), collapse = " & ")
  emit("type1_ccd", c("\\hline",
    " & \\multicolumn{4}{c|}{Proportion with $\\hat{k}=1$} & \\multicolumn{4}{c|}{Mean $\\hat{k}$} & \\multicolumn{4}{c|}{Mean \\textit{Sil}} \\\\ \\cline{2-13}",
    sprintf("$d$ & %s & %s & %s \\\\ \\hline", hdr, hdr, hdr),
    rows, "\\hline"))
  cat(sprintf("type1 ccd: P(k_hat = 1) %s at n = 50, %s at n >= 200; mean Sil %s\n",
              rng(t2$prop_k1[t2$n == "50"]), rng(t2$prop_k1[t2$n %in% c("200", "500")]), rng(t2$mean_si)))
}

# --- realhd: experiment 1, the six real data sets with d >= 13 ---------------
if (have("real_hd.csv", "real_hd_done.csv", "real_hd_baselines.csv", "real_hd_baselines_done.csv")) {
  source(here::here("revision_experiments/tr3/30_hd_load.R"))
  ROWS <- c("KS-CCDs", "RK-CCDs", "UN-CCDs", "DBSCAN", "MST", "K-means++", "Spectral", "Louvain")
  GIVEN_K <- c("K-means++", "Spectral")   # given the true k; k_hat marked with *, as in Table 5
  NAME <- c(wine = "wine", hepatitis = "hepatitis", lymphography = "lymphography", wdbc = "WDBC",
            vehicle = "vehicle", segmentation = "segmentation")
  hd <- tr3_load_hd(TR3_HD_DATASETS, verbose = FALSE)
  info <- data.frame(dataset = names(hd), n = sapply(hd, nrow), d = sapply(hd, ncol) - 1L,
                     k = sapply(hd, function(m) length(unique(m[, ncol(m)]))), stringsAsFactors = FALSE)
  info <- info[order(info$n), ]
  cols <- c("method", "dataset", "n", "d", "ari", "sil", "k_hat")
  ccd <- tr3_read_done(tr3_path("real_hd.csv"), tr3_path("real_hd_done.csv"), c("variant", "method", "dataset"))
  ccd <- ccd[ccd$variant == "hd", ]
  bas <- tr3_read_done(tr3_path("real_hd_baselines.csv"), tr3_path("real_hd_baselines_done.csv"), c("method", "dataset"))
  r <- rbind(ccd[, cols], bas[, cols])
  # one row per method and data set, with the n and d of the loaded data
  stopifnot(nrow(r) == length(ROWS) * nrow(info),
            setequal(paste(r$method, r$dataset), outer(ROWS, info$dataset, paste)))
  i <- match(r$dataset, info$dataset)
  g <- r$method %in% GIVEN_K
  stopifnot(all(as.integer(r$n) == info$n[i]), all(as.integer(r$d) == info$d[i]),
            all(as.integer(r$k_hat[g]) == info$k[i][g]))
  cell <- function(meth, ds) r[r$method == meth & r$dataset == ds, ]
  na3 <- function(x) ifelse(is.na(suppressWarnings(as.numeric(x))), "--", f3(x))
  rows <- vapply(ROWS, function(meth) {
    v <- vapply(info$dataset, function(ds) {
      x <- cell(meth, ds)
      sprintf("%s & %s & %s%s", na3(x$ari), na3(x$sil), x$k_hat, if (meth %in% GIVEN_K) "*" else "")
    }, "")
    sprintf("%s & %s \\\\ \\hline", meth, paste(v, collapse = " & "))
  }, "")
  emit("realhd", c("\\hline",
    sprintf("\\multirow{2}*{} & %s \\\\ \\cline{2-%d}",
            paste(sprintf("\\multicolumn{3}{|c|}{%s ($k$=%d)}", NAME[info$dataset], info$k), collapse = " & "),
            1 + 3 * nrow(info)),
    sprintf(" & %s \\\\ \\hline", paste(rep("\\textit{ARI} & \\textit{Sil} & $\\hat{k}$", nrow(info)), collapse = " & ")),
    rows))
  emit("realhd_data", sprintf("%s & %d & %d & %d \\\\ \\hline", NAME[info$dataset], info$n, info$d, info$k))
  # summary for the text, on the values as printed (3 decimals)
  a3 <- function(meth, ds) as.numeric(f3(cell(meth, ds)$ari))
  cat("realhd: n/d/k", paste(sprintf("%s %d/%d/%d", info$dataset, info$n, info$d, info$k), collapse = "; "), "\n")
  for (ds in info$dataset) {
    v <- vapply(ROWS, a3, 0, ds = ds)
    cat(sprintf("  %s: best ARI %.3f (%s); UN-CCDs rank %d of %d; k_hat %s\n", ds, max(v),
                paste(ROWS[v == max(v)], collapse = ", "), rank(-v, ties.method = "min")[["UN-CCDs"]], length(ROWS),
                paste(sprintf("%s %s", ROWS, vapply(ROWS, function(m) cell(m, ds)$k_hat, "")), collapse = ", ")))
  }
  for (o in setdiff(ROWS, "UN-CCDs")) {
    s <- sign(vapply(info$dataset, function(ds) a3("UN-CCDs", ds) - a3(o, ds), 0))
    cat(sprintf("  UN-CCDs vs %s: ARI higher in %d, lower in %d, equal in %d of %d\n",
                o, sum(s > 0), sum(s < 0), sum(s == 0), length(s)))
  }
  est <- setdiff(ROWS, GIVEN_K)
  ok <- vapply(est, function(m) sum(as.integer(vapply(info$dataset, function(ds) cell(m, ds)$k_hat, "")) == info$k), 0)
  cat("  k_hat = k:", paste(sprintf("%s %d", est, ok), collapse = ", "), "of", nrow(info), "\n")
  cat("  CCD seconds:", paste(sprintf("%s %s %s", ccd$method, ccd$dataset, ccd$seconds), collapse = "; "), "\n")
}
